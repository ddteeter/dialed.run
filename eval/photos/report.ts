/**
 * The report the photo eval writes.
 *
 * The request, the parse and the threshold rule all live in
 * `src/modules/safety/classifier/moderation.ts`, which this imports — so a
 * threshold read off this report is enforced by the same code that
 * produced it, rather than by a second implementation that looks the same.
 *
 * **There is no accuracy column, and that is not an omission.** Every photo
 * in the corpus is benign, so the only thing this can measure is the false
 * positive rate — which is exactly the number the threshold decision needs,
 * and exactly the number the packet asks for ("sports imagery triggers
 * false positives; tune before launch, not after complaints"). Recall is
 * unmeasured here and the report says so out loud, because a reader who
 * forgets that would read a clean table as "the classifier works".
 */
import type { CorpusEntry } from "./corpus";
import { imageCategories } from "../../src/modules/safety/classifier/moderation";
import type { ModerationResult } from "../../src/modules/safety/classifier/moderation";

export interface Scored {
  entry: CorpusEntry;
  result: ModerationResult | { error: string };
}

/**
Thresholds the report evaluates, so the choice is read off a table.
*/
const CANDIDATE_THRESHOLDS = [0.2, 0.5, 0.7, 0.9] as const;

export function reportFor(scored: readonly Scored[]): string {
  const ok = scored.filter(
    (row): row is { entry: CorpusEntry; result: ModerationResult } =>
      !("error" in row.result),
  );

  return [
    "# Photo screening eval (task 106)",
    "",
    "Generated by `npm run eval:photos`. Model: `omni-moderation-latest`.",
    "",
    "**Every photo in this corpus is benign.** This measures the false",
    "positive rate and nothing else — recall is NOT measured here, so a",
    'clean table below means "it does not flag ordinary running photos",',
    'never "it catches what we need it to catch".',
    "",
    `${String(ok.length)} of ${String(scored.length)} photos classified.`,
    "",
    thresholdTable(ok),
    "",
    flaggedSection(ok),
    "",
    exposureTable(ok),
    "",
    perPhotoTable(scored),
    "",
  ].join("\n");
}

/**
 * The decision table: how many benign photos each candidate threshold would
 * wrongly hide. A threshold with a zero here is one that costs nothing on
 * this corpus.
 */
function thresholdTable(
  ok: readonly { entry: CorpusEntry; result: ModerationResult }[],
): string {
  // Hoisted out of the template below: a template literal nested inside
  // another is a lint error, and the expression reads better named anyway.
  const thresholdHeadings = CANDIDATE_THRESHOLDS.map(
    (threshold) => `≥ ${String(threshold)}`,
  ).join(" | ");
  const header = [
    "## False positives by threshold",
    "",
    "How many of these benign photos each threshold would hide, per category.",
    "",
    `| category | ${thresholdHeadings} | max score |`,
    `| --- | ${CANDIDATE_THRESHOLDS.map(() => "---").join(" | ")} | --- |`,
  ];
  const rows = imageCategories.map((category) => {
    const scores = ok.map((row) => row.result.scores[category]);
    const counts = CANDIDATE_THRESHOLDS.map(
      (threshold) => scores.filter((score) => score >= threshold).length,
    );
    return `| \`${category}\` | ${counts.map(String).join(" | ")} | ${fixed(Math.max(0, ...scores))} |`;
  });
  return [...header, ...rows].join("\n");
}

/**
 * What the model's own boolean would have done. Reported because "we do not
 * use `flagged`" is a claim worth backing with the number it would have
 * cost.
 */
function flaggedSection(
  ok: readonly { entry: CorpusEntry; result: ModerationResult }[],
): string {
  const flagged = ok.filter((row) => row.result.flagged);
  return [
    "## The model's own `flagged` boolean",
    "",
    `${String(flagged.length)} of ${String(ok.length)} benign photos flagged.`,
    ...(flagged.length === 0
      ? ["", "None — on this corpus the boolean and a tuned threshold agree."]
      : [
          "",
          "This is why the code thresholds on `category_scores` instead:",
          "",
          ...flagged.map(
            (row) => `- \`${row.entry.file}\` — ${row.entry.note}`,
          ),
        ]),
  ].join("\n");
}

/**
 * The axis the false positive was predicted to live on. If scores climb
 * with exposure, the prediction was right and the threshold has to clear
 * the top of this column rather than the average.
 */
function exposureTable(
  ok: readonly { entry: CorpusEntry; result: ModerationResult }[],
): string {
  const buckets: CorpusEntry["exposure"][] = [
    "covered",
    "arms",
    "midriff",
    "shirtless",
  ];
  const rows = buckets.map((bucket) => {
    const scores = ok
      .filter((row) => row.entry.exposure === bucket)
      .map((row) => row.result.scores.sexual);
    if (scores.length === 0) return `| ${bucket} | — | — | 0 |`;
    const mean = scores.reduce((a, b) => a + b, 0) / scores.length;
    return `| ${bucket} | ${fixed(mean)} | ${fixed(Math.max(...scores))} | ${String(scores.length)} |`;
  });
  return [
    "## `sexual` score by how much skin is in frame",
    "",
    "| exposure | mean | max | n |",
    "| --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

function perPhotoTable(scored: readonly Scored[]): string {
  const rows = scored.map((row) => {
    if ("error" in row.result) {
      return `| \`${row.entry.file}\` | ${row.entry.exposure} | _${row.result.error}_ | | | |`;
    }
    const s = row.result.scores;
    return `| \`${row.entry.file}\` | ${row.entry.exposure} | ${fixed(s.sexual)} | ${fixed(s.violence)} | ${fixed(s["self-harm"])} | ${row.result.flagged ? "**yes**" : "no"} |`;
  });
  return [
    "## Per photo",
    "",
    "| file | exposure | sexual | violence | self-harm | flagged |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

/**
 * Four decimals: a threshold decision turns on whether a score is 0.0003 or
 * 0.3, and two decimals renders both as 0.00.
 */
function fixed(value: number): string {
  return value.toFixed(4);
}
